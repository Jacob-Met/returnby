import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH || '/opt/google/chrome/chrome',args:['--no-sandbox']});
try{
const p=await browser.newPage({viewport:{width:390,height:844}});
const url=process.env.RETURNBY_URL || 'http://127.0.0.1:18918';
await p.goto(url+'/batch-intake.html');
await p.locator('#batch-paste').fill('Store: Birch\nOrder #B4412\nOrder date: November 4, 2026\nItems may be returned within 21 days after delivery. Awaiting delivery.');
await p.locator('#batch-add').click();
assert.equal(await p.locator('[name=windowDays]').inputValue(),'21');
assert.equal(await p.getByRole('button',{name:'Keep purchase pending delivery'}).count(),1);
assert.match(await p.locator('[data-draft]').innerText(),/Confirm return clock start \(required\)/);
await p.locator('.batch-reviewed input').click();
assert.equal(await p.locator('.batch-reviewed input').isChecked(),false);
assert.match(await p.locator('#batch-error').innerText(),/Confirm the return-clock start/);
await p.reload();

await p.locator('#batch-paste').fill('Store: Meadow Clothing\nOrder #MC5718\nOrder date: November 2, 2026\nTotal: $118.00\nReturns accepted within 30 days of delivery. Sale items must be returned within 14 days.\nPRIVATE-RECEIPT-NOT-RETAINED');
await p.locator('#batch-add').click();
assert.equal(await p.locator('[name=windowDays]').inputValue(),'');
assert.match(await p.locator('.receipt-policy-evidence').innerText(),/Sale items must be returned within 14 days/);
await p.getByRole('button',{name:'Keep purchase pending delivery'}).click();
await p.goto(url+'/');
await p.reload();
assert.equal(await p.evaluate(()=>localStorage.getItem('returnby.v1')),null);
assert.equal(await p.evaluate(()=>JSON.stringify(localStorage).includes('PRIVATE-RECEIPT-NOT-RETAINED')),false);
await p.getByText('Awaiting delivery (1) — review purchases',{exact:true}).click();
await p.getByRole('button',{name:'Review delivery',exact:true}).click();
assert.equal(await p.locator('#preview [name=windowDays]').inputValue(),'');
await p.locator('#preview [name=windowStartDate]').fill('2026-11-10');
await p.getByRole('button',{name:'Save deadline to tracker',exact:true}).click();
assert.equal(await p.evaluate(()=>localStorage.getItem('returnby.v1')),null);
await p.locator('#preview [name=windowDays]').fill('14');
await p.getByRole('button',{name:'Save deadline to tracker',exact:true}).click();
const rows=await p.evaluate(()=>JSON.parse(localStorage.getItem('returnby.v1')));
assert.equal(rows.length,1);assert.equal(rows[0].orderDate,'2026-11-02');assert.equal(rows[0].windowStartDate,'2026-11-10');assert.equal(rows[0].windowDays,14);
assert.match(await p.locator('body').innerText(),/2026-11-24/);
await p.reload();assert.match(await p.locator('body').innerText(),/2026-11-24/);
console.log('PASS: conflicting returned clause remains visible; pending keeps unknown window and no raw text; explicit reviewed rule and delivery save the correct deadline across reload.');
}finally{await browser.close()}
