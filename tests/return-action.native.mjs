import {createRequire} from 'node:module';
import {createServer} from 'node:http';
import {readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {resolve,join,extname} from 'node:path';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright-core');
const root=resolve('dist');
const screenshot=name=>join(tmpdir(),name);
const types={'.html':'text/html','.js':'text/javascript','.css':'text/css','.svg':'image/svg+xml','.wasm':'application/wasm','.gz':'application/gzip'};
const server=createServer(async(req,res)=>{
 try {
  const url=new URL(req.url,'http://127.0.0.1');
  const file=join(root,url.pathname==='/'?'index.html':url.pathname.slice(1));
  const data=await readFile(file);
  res.setHeader('Content-Type',types[extname(file)]||'application/octet-stream');
  res.end(data);
 } catch {res.statusCode=404;res.end('Not found');}
});
await new Promise(done=>server.listen(0,'127.0.0.1',done));
const base='http://127.0.0.1:'+server.address().port;
const browser=await chromium.launch({executablePath:'/opt/google/chrome/chrome',args:['--no-sandbox']});
try {
 const context=await browser.newContext({viewport:{width:390,height:844},acceptDownloads:true});
 const page=await context.newPage();
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const text='Store: Cedar Goods\nOrder #: RB-319\nOrder date: November 1, 2026\nTotal: $42\nReturns must be shipped within 14 days. Returned parcels must arrive at our warehouse within 21 days.';
 await page.goto(base);
 await page.locator('#paste').fill(text);
 await page.locator('#find').click();
 assert.equal(await page.locator('#preview [name=windowDays]').inputValue(),'');
 assert.equal(await page.locator('#preview [name=deadlineRequirement]').getAttribute('required'),'');
 assert.match(await page.locator('#preview').innerText(),/Shipping and merchant arrival can have different dates/i);
 assert.match(await page.locator('#preview').innerText(),/Returned parcels must arrive/);
 await page.locator('#preview [name=deadlineRequirement]').scrollIntoViewIfNeeded();
 await page.screenshot({path:screenshot('returnby-action-review-phone.png')});
 await page.locator('#preview [name=windowDays]').fill('14');
 await page.locator('#preview button[type=submit]').click();
 assert.equal(await page.evaluate(()=>localStorage.getItem('returnby.v1')),null);
 await page.locator('#preview [name=deadlineRequirement]').selectOption('arrive-by');
 await page.locator('#preview button[type=submit]').click();
 const orders=await page.evaluate(()=>JSON.parse(localStorage.getItem('returnby.v1')));
 assert.equal(orders.length,1);
 assert.equal(orders[0].deadlineRequirement,'arrive-by');
 assert.match(await page.locator('#list').innerText(),/MERCHANT MUST RECEIVE BY/);
 await page.screenshot({path:screenshot('returnby-return-action-phone.png'),fullPage:true});
 await page.goto(base+'/trip-checklist.html');
 await page.locator('#trip-date').fill('2026-11-12');
 await page.locator('#order-options input[type=checkbox]').first().check();
 assert.match(await page.locator('#packing-planner').innerText(),/Allow transit time/);
 await page.goto(base+'/batch-intake.html');
 await page.locator('#batch-paste').fill(text.replace('RB-319','RB-320'));
 await page.locator('#batch-add').click();
 const action=page.locator('#batch-drafts [data-field=deadlineRequirement]');
 assert.equal(await action.isVisible(),true);
 assert.equal(await action.getAttribute('required'),'');
 await action.scrollIntoViewIfNeeded();
 await page.screenshot({path:screenshot('returnby-action-batch-review-phone.png')});
 await page.locator('#batch-drafts [data-field=windowDays]').fill('14');
 await page.locator('#batch-drafts [data-reviewed]').first().click();
 assert.equal(await page.locator('#batch-drafts [data-reviewed]').first().isChecked(),false);
 assert.match(await page.locator('#batch-error').innerText(),/Choose what must happen/);
 await action.selectOption('ship-by');
 await page.locator('#batch-drafts [data-reviewed]').first().check();
 await page.locator('#batch-preview').click();
 assert.equal(await page.locator('#batch-final').isVisible(),true);
 await page.locator('#batch-save').click();
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('returnby.v1')));
 assert.equal(saved.length,2);
 assert.equal(saved[1].deadlineRequirement,'ship-by');
 await page.screenshot({path:screenshot('returnby-batch-action-phone.png'),fullPage:true});
 // The receipt text is deliberately absent after pending/reload. Its unresolved
 // action requirement must still block saving a falsely generic deadline.
 await page.evaluate(()=>localStorage.clear());
 await page.goto(base);
 await page.locator('#paste').fill('Store: Harbor Market\\nOrder #: RB-321\\nOrder date: November 1, 2026\\nTotal: $42\\nReturns must be shipped within 14 days after delivery. Awaiting delivery.'.replaceAll('\\n','\n'));
 await page.locator('#find').click();
 await page.locator('#save-pending-delivery').click();
 const pending=await page.evaluate(()=>JSON.parse(localStorage.getItem('returnby.pending-deliveries')));
 assert.equal(pending.purchases[0].fields.deadlineActionReviewRequired,'yes');
 assert.equal(await page.evaluate(()=>localStorage.getItem('returnby.v1')),null);
 await page.reload();
 await page.locator('#pending-desk summary').click();
 await page.getByRole('button',{name:'Review delivery'}).click();
 assert.equal(await page.locator('#preview [name=deadlineRequirement]').getAttribute('required'),'');
 await page.locator('#preview [name=windowStartDate]').fill('2026-11-07');
 await page.locator('#preview button[type=submit]').click();
 assert.equal(await page.evaluate(()=>localStorage.getItem('returnby.v1')),null);
 await page.locator('#preview [name=deadlineRequirement]').selectOption('ship-by');
 await page.locator('#preview button[type=submit]').click();
 const resumed=await page.evaluate(()=>JSON.parse(localStorage.getItem('returnby.v1')));
 assert.equal(resumed.length,1);
 assert.equal(resumed[0].deadlineRequirement,'ship-by');
 assert.deepEqual(errors,[]);
 console.log('PASS production browser 390x844: conflicting handoffs blocked, merchant arrival saved and used by trip, batch ship-by selected, pending delivery still requires action after reload; no JS errors.');
 await context.close();
} finally {
 await browser.close();
 await new Promise(done=>server.close(done));
}
