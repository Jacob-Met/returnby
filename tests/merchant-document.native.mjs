import {createRequire} from 'node:module';
import {createServer} from 'node:http';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {join,resolve,extname} from 'node:path';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright-core');
const root=resolve(process.env.RETURNBY_DIST||'dist');
const types={'.html':'text/html','.js':'text/javascript','.css':'text/css','.wasm':'application/wasm','.svg':'image/svg+xml'};
const server=createServer(async(req,res)=>{
  try {
    const path=new URL(req.url,'http://127.0.0.1').pathname;
    const filename=path==='/'?'index.html':path.slice(1);
    const bytes=await readFile(join(root,filename));
    res.setHeader('Content-Type',types[extname(filename)]||'application/octet-stream');
    res.end(bytes);
  } catch{res.statusCode=404;res.end('Not found');}
});
await new Promise(done=>server.listen(0,'127.0.0.1',done));
const origin='http://127.0.0.1:'+server.address().port;
const browser=await chromium.launch({executablePath:'/opt/google/chrome/chrome',args:['--no-sandbox']});
try {
  const ctx=await browser.newContext({viewport:{width:390,height:844},acceptDownloads:true});
  const page=await ctx.newPage();
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(origin);
  await page.locator('#manual-open').click();
  await page.locator('#manual-form [name=merchant]').fill('Seabird Outfitters');
  await page.locator('#manual-form [name=orderDate]').fill('2026-11-08');
  await page.locator('#manual-form [name=windowDays]').fill('30');
  await page.locator('#manual-form [name=orderNo]').fill('SB-401');
  await page.locator('#manual-form button[type=submit]').click();
  await page.locator('#manual-dialog').waitFor({state:'hidden'});
  const order=(await page.evaluate(()=>JSON.parse(localStorage.getItem('returnby.v1'))))[0];
  const image=Buffer.from(await page.evaluate(()=>{
    const canvas=document.createElement('canvas');canvas.width=500;canvas.height=300;
    const c=canvas.getContext('2d');c.fillStyle='white';c.fillRect(0,0,500,300);
    c.fillStyle='black';c.font='bold 27px sans-serif';c.fillText('SEABIRD RETURN',35,58);
    c.fillText('AUTHORIZATION',35,95);
    for(let y=0;y<13;y++)for(let x=0;x<13;x++) if((x*7+y*11+x*y)%5<3)c.fillRect(35+x*12,118+y*12,10,10);
    c.font='18px sans-serif';c.fillText('SB-401 / MERCHANT FILE',240,240);
    return canvas.toDataURL('image/png').split(',')[1];
  }),'base64');
  await page.locator('#list [data-merchant-document]').click();
  await page.locator('.merchant-document-dialog input[type=file]').setInputFiles({name:'seabird-issued-QR.png',mimeType:'image/png',buffer:image});
  await page.locator('.merchant-document-preview img').waitFor({state:'visible'});
  const downloadStarted=page.waitForEvent('download');
  await page.locator('[data-merchant-download]').click();
  assert.deepEqual(await readFile(await (await downloadStarted).path()),image);
  const out='/workspace/tmp/returnby-merchant-'+process.pid;await mkdir(out,{recursive:true});
  await page.screenshot({path:out+'/return-document-phone.png'});
  await page.locator('.merchant-document-dialog .receipt-proof-close').click();
  await page.reload();
  await page.locator('#list [data-merchant-document]').click();
  await page.locator('.merchant-document-preview img').waitFor({state:'visible'});
  assert.match(await page.locator('.merchant-document-dialog .receipt-proof-message').innerText(),/ready to open/);
  await page.locator('.merchant-document-dialog .receipt-proof-close').click();
  await page.locator('#backup-heading').click();
  const backupStarted=page.waitForEvent('download');
  await page.locator('#backup-export').click();
  const backup=Buffer.from(await readFile(await (await backupStarted).path()));
  const envelope=JSON.parse(backup.toString());
  assert.equal(envelope.version,13);
  assert.equal(envelope.merchantDocuments.length,1);
  assert.equal(envelope.merchantDocuments[0].id,order.id);
  await page.goto(origin+'/trip-checklist.html');
  await page.locator('#trip-date').fill('2026-11-15');
  await page.locator('#order-options input[type=checkbox]').first().check();
  await page.locator('#preview-trip').click();
  await page.locator('#checklist-preview #merchant-documents img').waitFor({state:'visible'});
  const sheetStarted=page.waitForEvent('download');
  await page.locator('#download-checklist').click();
  const sheet=await readFile(await (await sheetStarted).path(),'utf8');
  assert(sheet.includes('data:image/png;base64,'+image.toString('base64')));
  const sheetFile=out+'/offline-trip.html';await writeFile(sheetFile,sheet);
  await page.goto('file://'+sheetFile);
  assert.equal(await page.locator('#merchant-documents img').count(),1);
  assert.equal(await page.locator('#merchant-documents img').evaluate(el=>el.naturalWidth>0),true);
  await page.setViewportSize({width:1440,height:900});
  await page.screenshot({path:out+'/return-document-offline-desktop.png'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  const restored=await browser.newContext({viewport:{width:390,height:844},acceptDownloads:true});
  const fresh=await restored.newPage();fresh.on('pageerror',error=>errors.push(error.message));
  await fresh.goto(origin);
  await fresh.locator('#backup-heading').click();
  await fresh.locator('#backup-file').setInputFiles({name:'returnby-backup.json',mimeType:'application/json',buffer:backup});
  await fresh.locator('#backup-apply').click();
  await fresh.locator('#list [data-merchant-document]').click();
  await fresh.locator('.merchant-document-preview img').waitFor({state:'visible'});
  assert.equal(await fresh.locator('.merchant-document-preview img').evaluate(el=>el.naturalWidth),500);
  assert.deepEqual(errors,[]);
  console.log('PASS full packaged 390/1440: real saved QR upload, exact download, reload, offline printable sheet, version13 backup and new-browser restore; output '+out);
  await restored.close();await ctx.close();
} finally {await browser.close();await new Promise(done=>server.close(done));}
