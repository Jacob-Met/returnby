import {createRequire} from 'node:module';
import {createServer} from 'node:http';
import {readFile} from 'node:fs/promises';
import {resolve,join,extname} from 'node:path';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright-core');
const root=resolve('dist');
const types={'.html':'text/html','.js':'text/javascript','.css':'text/css','.svg':'image/svg+xml','.wasm':'application/wasm','.gz':'application/gzip','.js.gz':'text/javascript'};
const server=createServer(async(req,res)=>{
 try{
  const url=new URL(req.url,'http://127.0.0.1');
  const filename=join(root,url.pathname==='/'?'index.html':url.pathname.slice(1));
  const data=await readFile(filename);
  res.setHeader('Content-Type',types[extname(filename)]||'application/octet-stream');
  res.end(data);
 }catch(e){res.statusCode=404;res.end('Not found');}
});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const origin='http://127.0.0.1:'+server.address().port;
const browser=await chromium.launch({executablePath:'/opt/google/chrome/chrome',args:['--no-sandbox']});
try{
 const ctx=await browser.newContext({viewport:{width:390,height:844},acceptDownloads:true});
 const page=await ctx.newPage();
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(origin);
 await page.locator('#paste').fill('Store: North Trail\nOrder #RB-200\nOrder date: November 1, 2026\nDelivered: November 7, 2026\nTotal: $88.10\nReturns accepted within 30 days of delivery.');
 await page.locator('#find').click();
 const evidence='https://merchant.example/return-label?order=RB-200&kind=QR';
 await page.locator('#preview [name=returnEvidenceUrl]').fill(evidence);
 await page.locator('#preview [name=deadlineRequirement]').selectOption('ship-by');
 await page.locator('#save-pending-delivery').click();
 const pending=await page.evaluate(()=>JSON.parse(localStorage.getItem('returnby.pending-deliveries')));
 assert.equal(pending.purchases[0].fields.returnEvidenceUrl,evidence);
 assert.equal(pending.purchases[0].fields.deadlineRequirement,'ship-by');
 assert.equal(await page.evaluate(()=>localStorage.getItem('returnby.v1')),null);
 await page.reload();
 await page.locator('#pending-desk summary').click();
 await page.getByRole('button',{name:'Review delivery'}).click();
 assert.equal(await page.locator('#preview [name=returnEvidenceUrl]').inputValue(),evidence);
 assert.equal(await page.locator('#preview [name=deadlineRequirement]').inputValue(),'ship-by');
 await page.locator('#preview [name=windowStartDate]').fill('2026-11-07');
 await page.locator('#preview button[type=submit]').click();
 const rows=await page.evaluate(()=>JSON.parse(localStorage.getItem('returnby.v1')));
 assert.equal(rows[0].returnEvidenceUrl,evidence);
 assert.equal(rows[0].deadlineRequirement,'ship-by');
 assert.equal(rows[0].windowStartDate,'2026-11-07');
 assert.equal((await page.evaluate(()=>JSON.parse(localStorage.getItem('returnby.pending-deliveries')))).purchases.length,0);
 const link=page.locator('#list a.return-document, #list .return-document a').first();
 assert.equal(await link.getAttribute('href'),evidence);
 await page.locator('#list [data-edit]').first().click();
 const revised='https://merchant.example/updated-label?order=RB-200';
 await page.locator('#edit-return-evidence-url').fill(revised);
 await page.locator('#edit-deadline-requirement').selectOption('drop-off-by');
 await page.locator('#edit-save').click();
 assert.equal((await page.evaluate(()=>JSON.parse(localStorage.getItem('returnby.v1'))))[0].returnEvidenceUrl,revised);
 assert.equal((await page.evaluate(()=>JSON.parse(localStorage.getItem('returnby.v1'))))[0].deadlineRequirement,'drop-off-by');
 await page.reload();
 assert.equal(await page.locator('#list .return-document a').first().getAttribute('href'),revised);
 await page.locator('#backup-heading').click();
 const downloadPromise=page.waitForEvent('download');
 await page.locator('#backup-export').click();
 const download=await downloadPromise;
 const backup=JSON.parse(await readFile(await download.path(),'utf8'));
 assert.equal(backup.version,8);
 assert.equal(backup.orders[0].deadlineRequirement,'drop-off-by');
 assert.equal(backup.orders[0].returnEvidenceUrl,revised);
 await page.goto(origin+'/trip-checklist.html');
 await page.locator('#trip-date').fill('2026-11-12');
 await page.locator('#order-options input[type=checkbox]').first().check();
 assert.equal(await page.locator('#packing-planner .packing-evidence-link').getAttribute('href'),revised);
 assert.match(await page.locator('#packing-planner').innerText(),/Drop off by/);
 assert.match(await page.locator('#packing-planner').innerText(),/Hand the item/);
 await page.locator('#preview-trip').click();
 assert.equal(await page.locator('#checklist-preview .sheet-evidence a').first().getAttribute('href'),revised);
 assert.match(await page.locator('#checklist-preview').innerText(),/DROP OFF BY/);
 await page.screenshot({path:'/workspace/tmp/returnby-proof-trip-phone.png',fullPage:true});
 await page.setViewportSize({width:1440,height:900});
 await page.screenshot({path:'/workspace/tmp/returnby-proof-trip-desktop.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false);
 await page.goto(origin);
 await page.locator('#manual-open').click();
 await page.locator('#manual-form [name=merchant]').fill('Harbor Books');
 await page.locator('#manual-form [name=orderDate]').fill('2026-11-08');
 await page.locator('#manual-form [name=windowDays]').fill('30');
 await page.locator('#manual-form [name=returnEvidenceUrl]').fill('https://harbor.example/receipt/0003');
 await page.locator('#manual-form [name=deadlineRequirement]').selectOption('arrive-by');
 await page.locator('#manual-form button[type=submit]').click();
 assert.equal((await page.evaluate(()=>JSON.parse(localStorage.getItem('returnby.v1'))))[1].returnEvidenceUrl,'https://harbor.example/receipt/0003');
 assert.equal((await page.evaluate(()=>JSON.parse(localStorage.getItem('returnby.v1'))))[1].deadlineRequirement,'arrive-by');
 assert.match(await page.locator('#list').innerText(),/MERCHANT MUST RECEIVE BY/);
 await page.screenshot({path:'/workspace/tmp/returnby-proof-tracker-desktop.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('PASS real packaged phone+desktop: pending ship-by, reopened and changed to drop-off, backed up v8, printable trip, manual arrive-by; no JS page errors or desktop overflow');
 await ctx.close();
}finally{await browser.close();await new Promise(done=>server.close(done));}
